// Flattened array of all cities with state metadata for search autocomplete
export const ALL_INDIAN_CITIES = Object.entries(INDIAN_LOCATIONS_MASTER).flatMap(
  ([state, cities]) => cities.map((city) => ({ city, state }))
);

// Helper: List all available states
export function getIndianStates() {
  return Object.keys(INDIAN_LOCATIONS_MASTER);
}

// Helper: Get cities for a specified state
export function getCitiesForState(stateName) {
  if (!stateName || stateName === "All States" || stateName === "All India") {
    const allCities = Object.values(INDIAN_LOCATIONS_MASTER).flat();
    return ["All Cities", ...new Set(allCities)];
  }
  const stateCities = INDIAN_LOCATIONS_MASTER[stateName] || [];
  return [`All Cities (${stateName})`, ...stateCities];
}

// Helper: Search cities by query string (matches city name or state name)
export function searchCitiesMaster(query, limit = 15) {
  if (!query || !query.trim()) {
    return ALL_INDIAN_CITIES.slice(0, limit);
  }
  const cleanQ = query.trim().toLowerCase();
  
  const matches = ALL_INDIAN_CITIES.filter(
    (item) =>
      item.city.toLowerCase().includes(cleanQ) ||
      item.state.toLowerCase().includes(cleanQ)
  );

  // Exact startsWith matches rank higher
  matches.sort((a, b) => {
    const aStartsWith = a.city.toLowerCase().startsWith(cleanQ);
    const bStartsWith = b.city.toLowerCase().startsWith(cleanQ);
    if (aStartsWith && !bStartsWith) return -1;
    if (!aStartsWith && bStartsWith) return 1;
    return a.city.localeCompare(b.city);
  });

  return matches.slice(0, limit);
}
